"""Move a project folder and rewrite every place an agent recorded its path.

Two phases. `plan()` reads everything and computes each change in memory; nothing is written.
`execute()` backs up every file it will touch, journals each step, applies the plan, and
rolls everything back if any step fails. `undo()` replays a journal backwards.

What is rewritten (registries, indexes, trust lists, session metadata) and what is NOT
(conversation bodies) follows docs/RISKS.md:

  rewritten   Claude Code: projects/<encoded> folder name, "cwd" fields in its .jsonl files,
              ~/.claude.json, history.jsonl "project"; desktop session JSON, git-worktrees.json
              Codex: threads.cwd, project_roots.path, codex-dev.db catalog and automations,
              .codex-global-state.json, config.toml [projects.'...']
              Antigravity/Gemini: conversation_summaries.workspace_uris, config/*.json,
              trust lists, projects.json, .project_root files, storage.json, state.vscdb
  never       Codex rollouts (thread_history keeps byte offsets into them), Antigravity
              conversations (*.db steps / *.pb protobuf), brain transcripts,
              VS Code-style workspaceStorage (regenerated by the app)
"""
