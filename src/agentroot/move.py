# ----------------------------------------------------------------------------- plan model


@dataclass
class TextEdit:
    path: str
    store: str
    count: int
    old_sha: str
    new_text: str = field(repr=False, default="")


@dataclass
class SqlEdit:
    db: str
    table: str
    column: str
    rowid: int
    old: str
    new: str


@dataclass
class DirRename:
    old: str
    new: str


@dataclass
class Plan:
    src: str
    dst: str
    move_folder: bool
    text: list[TextEdit] = field(default_factory=list)
    sql: list[SqlEdit] = field(default_factory=list)
    renames: list[DirRename] = field(default_factory=list)
    git_repair: list[tuple[str, list[str]]] = field(default_factory=list)  # (main repo after move, worktrees)
    untouched: dict[str, int] = field(default_factory=dict)  # store -> count kept with the old path on purpose
    warnings: list[str] = field(default_factory=list)

    @property
    def change_count(self) -> int:
        return sum(t.count for t in self.text) + len(self.sql) + len(self.renames)


class MoveError(RuntimeError):
    pass


# ----------------------------------------------------------------------------- text rewriting

_JSON_STR = re.compile(r'"((?:[^"\\\n]|\\.)*)"')
_GRANT = re.compile(r"\(([A-Za-z]:[\\/][^()]*)\)")


def _remap_str(s: str, src: str, dst: str) -> str | None:
    if len(s) > 1000 or "\n" in s:
        return None
    new = paths.remap(s, src, dst)
    if new is not None:
        return new
    if "(" in s:  # permission grants: read_file(C:\proj\x)
        out = _GRANT.sub(lambda m: "(" + (paths.remap(m.group(1), src, dst) or m.group(1)) + ")", s)
        return out if out != s else None
    return None


def rewrite_json_text(text: str, src: str, dst: str, keys: tuple[str, ...] | None = None) -> tuple[str, int]:
    """Rewrite path strings in JSON/JSONL text, keeping every other byte as it was.

    With `keys`, only string values of those keys change (used for session files, where the
    rest of the line is conversation content that must stay untouched).
    """
    count = 0

    def sub_token(inner: str) -> str | None:
        try:
            s = json.loads(f'"{inner}"')
        except ValueError:
            return None
        new = _remap_str(s, src, dst)
        return None if new is None else json.dumps(new, ensure_ascii=False)[1:-1]

    if keys:
        pat = re.compile(r'("(?:%s)"\s*:\s*)"((?:[^"\\\n]|\\.)*)"' % "|".join(map(re.escape, keys)))

        def repl(m: re.Match) -> str:
            nonlocal count
            new = sub_token(m.group(2))
            if new is None:
                return m.group(0)
            count += 1
            return f'{m.group(1)}"{new}"'
    else:
        pat = _JSON_STR

        def repl(m: re.Match) -> str:
            nonlocal count
            new = sub_token(m.group(1))
            if new is None:
                return m.group(0)
            count += 1
            return f'"{new}"'

    return pat.sub(repl, text), count


_TOML_PROJECT = re.compile(r"^(\[projects\.)(['\"])(.+?)\2(\]\s*)$", re.M)


def rewrite_codex_toml(text: str, src: str, dst: str) -> tuple[str, int]:
    count = 0

    def repl(m: re.Match) -> str:
        nonlocal count
        raw = m.group(3) if m.group(2) == "'" else m.group(3).replace("\\\\", "\\")
        new = paths.remap(raw, src, dst)
        if new is None:
            return m.group(0)
        count += 1
        if m.group(2) == '"':
            new = new.replace("\\", "\\\\")
        return f"{m.group(1)}{m.group(2)}{new}{m.group(2)}{m.group(4)}"

    return _TOML_PROJECT.sub(repl, text), count


def rewrite_plain(text: str, src: str, dst: str) -> tuple[str, int]:
    body = text.strip()
    new = paths.remap(body, src, dst)
    return (text.replace(body, new), 1) if new else (text, 0)


# ----------------------------------------------------------------------------- planning


def _read(path: str) -> str:
    with open(path, "rb") as f:
        return f.read().decode("utf-8", errors="surrogateescape")


def _sha(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


class _Planner:
    def __init__(self, user_home: str, src: str, dst: str, move_folder: bool):
        self.home = user_home
        self.plan = Plan(paths.display(src), paths.display(dst), move_folder)
        self.src, self.dst = self.plan.src, self.plan.dst
        self._seen: set[str] = set()

    # -- helpers
    def text(self, path: str, store: str, fn, *args) -> None:
        if not os.path.isfile(path):
            return
        real = paths.key(os.path.realpath(path))
        if real in self._seen:  # same physical file reached through a junction
            return
        self._seen.add(real)
        try:
            old = _read(path)
        except OSError as e:
            self.plan.warnings.append(f"cannot read {path}: {e}")
            return
        new, n = fn(old, self.src, self.dst, *args)
        if n:
            self.plan.text.append(TextEdit(path, store, n, _sha(path), new))

    def sql(self, db: str, table: str, column: str, json_text: bool = False) -> None:
        if not os.path.isfile(db):
            return
        with open_copy(db) as con:
            if not has_table(con, table) or column not in columns(con, table):
                return
            for rowid, value in con.execute(f'select rowid, "{column}" from "{table}" where "{column}" is not null'):
                if isinstance(value, bytes):
                    try:
                        value = value.decode("utf-8")
                    except UnicodeDecodeError:
                        continue
                if not isinstance(value, str):
                    continue
                if json_text:
                    new, n = rewrite_json_text(value, self.src, self.dst)
                    if not n:
                        continue
                else:
                    new = paths.remap(value, self.src, self.dst)
                    if new is None:
                        continue
                self.plan.sql.append(SqlEdit(db, table, column, rowid, value, new))

    # -- agents
    def claude(self) -> None:
        enc_src = paths.claude_project_dir(self.src).lower()
        for home in claude.homes(self.home):
            if home.agent == claude.DESKTOP:
                for f in glob.glob(os.path.join(home.path, "claude-code-sessions", "**", "*.json"), recursive=True):
                    self.text(f, "claude-desktop session", rewrite_json_text, ("cwd", "originCwd", "worktreePath", "gitAnchorsFolderRealpath"))
                self.text(os.path.join(home.path, "git-worktrees.json"), "claude-desktop git-worktrees.json", rewrite_json_text)
                continue
            for cfg in (os.path.join(os.path.dirname(home.path), ".claude.json") if os.path.basename(home.path) == ".claude" else "",
                        os.path.join(home.path, ".claude.json")):
                if cfg:
                    self.text(cfg, ".claude.json", rewrite_json_text)
            self.text(os.path.join(home.path, "history.jsonl"), "claude history.jsonl", rewrite_json_text, ("project",))
            if home.note.startswith(claude.SHARED_PREFIX):
                continue
            projects = os.path.join(home.path, "projects")
            by_dir: dict[str, list[str]] = {}
            for s in claude.sessions(home):
                if s.path and paths.is_within(s.path, self.src):
                    by_dir.setdefault(os.path.dirname(os.path.join(home.path, s.store)), []).append(s.path)
            # Folder names are lossy ("-" stands for any non-alphanumeric), so "C--a-proj-x" could be
            # C:\a\proj\x or the sibling C:\a\proj-x. A folder is renamed only when a session inside it
            # really lives under src, and either its name encodes that session's cwd or it starts
            # with src's encoding (a session filed under a sibling worktree's folder, seen in practice).
            for d, cwds in by_dir.items():
                for f in glob.glob(os.path.join(d, "**", "*.jsonl"), recursive=True):
                    self.text(f, "claude session cwd", rewrite_json_text, ("cwd",))
                name = os.path.basename(d)
                owner = next((c for c in cwds if paths.claude_project_dir(c).lower() == name.lower()), None)
                if owner:
                    target = paths.claude_project_dir(paths.remap(owner, self.src, self.dst))
                elif name.lower() == enc_src or name.lower().startswith(enc_src + "-"):
                    target = paths.claude_project_dir(self.dst) + name[len(enc_src):]
                else:
                    continue  # filed under an unrelated project's folder: fix cwd, keep the folder
                if target != name:
                    self.plan.renames.append(DirRename(d, os.path.join(projects, target)))

    def codex(self) -> None:
        for home in codex.homes(self.home):
            for db in codex._state_dbs(home):
                self.sql(db, "threads", "cwd")
                self.sql(db, "project_roots", "path")
            dev = os.path.join(home.path, "sqlite", "codex-dev.db")
            self.sql(dev, "local_thread_catalog", "cwd")
            self.sql(dev, "automations", "cwds", json_text=True)
            self.sql(dev, "automations", "local_environment_config_path")
            self.text(os.path.join(home.path, ".codex-global-state.json"), "codex global state", rewrite_json_text)
            self.text(os.path.join(home.path, "config.toml"), "codex config.toml", rewrite_codex_toml)
            kept = sum(1 for f in codex._rollouts(home) if paths.is_within(codex.session_meta(f).get("cwd") or "", self.src))
            if kept:
                self.plan.untouched["codex rollouts (conversation bodies)"] = kept

    def antigravity(self) -> None:
        gem = os.path.join(self.home, ".gemini")
        for home in antigravity.homes(self.home):
            if home.note == "backup copy":
                continue
            db = os.path.join(home.path, "conversation_summaries.db")
            self.sql(db, "conversation_summaries", "workspace_uris", json_text=True)
            convs = glob.glob(os.path.join(home.path, "conversations", "*"))
            if convs and os.path.isfile(db):
                n = sum(1 for e in self.plan.sql if e.db == db)
                if n:
                    self.plan.untouched[f"antigravity conversations ({os.path.basename(home.path)})"] = n
        for f in glob.glob(os.path.join(gem, "config", "projects", "*.json")) + [
            os.path.join(gem, "config", "config.json"),
            os.path.join(gem, "antigravity-cli", "settings.json"),
            os.path.join(gem, "projects.json"),
            os.path.join(gem, "trustedFolders.json"),
        ]:
            self.text(f, "antigravity/gemini config", rewrite_json_text)
        for f in glob.glob(os.path.join(gem, "history", "*", ".project_root")) + glob.glob(os.path.join(gem, "tmp", "*", ".project_root")):
            self.text(f, "gemini .project_root", rewrite_plain)
        appdata = os.environ.get("APPDATA", os.path.join(self.home, "AppData", "Roaming"))
        user = os.path.join(appdata, "Antigravity", "User")
        self.text(os.path.join(user, "globalStorage", "storage.json"), "antigravity storage.json", rewrite_json_text)
        self.sql(os.path.join(user, "globalStorage", "state.vscdb"), "ItemTable", "value", json_text=True)

    def git(self) -> None:
        src = self.src
        dotgit = os.path.join(src, ".git")
        if os.path.isdir(dotgit):
            wts = []
            for gd in glob.glob(os.path.join(dotgit, "worktrees", "*", "gitdir")):
                try:
                    with open(gd, encoding="utf-8") as f:
                        wt_git = f.read().strip()
                except OSError:
                    continue
                wt = os.path.dirname(paths.display(wt_git))
                wts.append(paths.remap(wt, src, self.dst) or wt)
            self.plan.git_repair.append((self.dst, wts))
        elif os.path.isfile(dotgit):
            info = gitinfo.find(src)
            if info and info.main_root:
                main = paths.remap(info.main_root, src, self.dst) or info.main_root
                self.plan.git_repair.append((main, [self.dst]))


def _validate(t: TextEdit) -> None:
    """The rewritten file must still parse, and must not have gained duplicate keys
    (two ~/.claude.json projects collapsing into one key would silently drop one)."""
    def no_dupes(pairs):
        keys = [k for k, _ in pairs]
        if len(keys) != len(set(keys)):
            dup = next(k for k in keys if keys.count(k) > 1)
            raise MoveError(f"{t.path}: after the move two entries would share the key {dup!r}; resolve it first")
        return dict(pairs)

    p = t.path.lower()
    try:
        if p.endswith(".jsonl"):
            # split on \n only: str.splitlines() also breaks on \u2028 and \x85, which JSON allows inside strings
            for line in t.new_text.split("\n"):
                if line.strip():
                    json.loads(line, object_pairs_hook=no_dupes)
        elif p.endswith(".json"):
            json.loads(t.new_text, object_pairs_hook=no_dupes)
        elif p.endswith(".toml"):
            import tomllib
            tomllib.loads(t.new_text)
    except MoveError:
        raise
    except ValueError as e:
        raise MoveError(f"{t.path}: rewritten file would not parse ({e})") from e


def plan(user_home: str, src: str, dst: str, move_folder: bool = True) -> Plan:
    p = _Planner(user_home, src, dst, move_folder)
    for adapter in (claude, codex, antigravity):
        for h in adapter.homes(user_home):
            if paths.is_within(h.path, p.src):
                raise MoveError(f"{p.src} contains the agent data directory {h.path}; refusing to move it")
    if move_folder:
        if not os.path.isdir(p.src):
            raise MoveError(f"source folder does not exist: {p.src}")
        if os.path.exists(p.dst):
            raise MoveError(f"destination already exists: {p.dst}")
        if paths.is_within(p.dst, p.src):
            raise MoveError("destination is inside the source")
        p.git()
    p.claude()
    p.codex()
    p.antigravity()
    for t in p.plan.text:
        _validate(t)
    return p.plan


